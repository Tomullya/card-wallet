#!/usr/bin/env python3
"""Build docs/qa/traceability-matrix.md: business requirement → automated tests.

Requirement IDs come from the headings in docs/requirements/*.md.
Test coverage comes from @pytest.mark.req("<ID>", ...) markers on the tests.
Exit code 1 if a requirement has no test or a test names an unknown ID.
"""

import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQ_DIR = ROOT / "docs" / "requirements"
OUTPUT = ROOT / "docs" / "qa" / "traceability-matrix.md"
HEADING = re.compile(r"^##\s+((?:BR-[A-Z]+-\d{2})|(?:NFR-\d{2}))\s+(.+?)\s*$")


def load_requirements(req_dir: Path) -> dict[str, str]:
    """Requirement ID → title, in document order (files sorted by name)."""
    requirements: dict[str, str] = {}
    for path in sorted(req_dir.glob("*.md")):
        for line in path.read_text().splitlines():
            if match := HEADING.match(line):
                requirements[match.group(1)] = match.group(2)
    return requirements


def render_matrix(requirements: dict[str, str], coverage: dict[str, list[str]]) -> str:
    covered = sum(1 for req_id in requirements if coverage.get(req_id))
    lines = [
        "# Traceability matrix",
        "",
        "Generated by `scripts/traceability.py` from the `@pytest.mark.req` markers. "
        "Do not edit by hand.",
        "",
        f"Covered: {covered} / {len(requirements)}",
        "",
        "| ID | Requirement | Tests | Count |",
        "|---|---|---|---|",
    ]
    for req_id, title in requirements.items():
        tests = sorted(coverage.get(req_id, []))
        cell = "<br>".join(f"`{t}`" for t in tests) if tests else "**NOT COVERED**"
        lines.append(f"| {req_id} | {title} | {cell} | {len(tests)} |")
    return "\n".join(lines) + "\n"


def check(requirements: dict[str, str], coverage: dict[str, list[str]]) -> list[str]:
    problems = [
        f"Unknown requirement ID in tests: {req_id} (used by {', '.join(sorted(tests)[:3])})"
        for req_id, tests in sorted(coverage.items())
        if req_id not in requirements
    ]
    problems += [
        f"Requirement not covered by any test: {req_id}"
        for req_id in requirements
        if not coverage.get(req_id)
    ]
    return problems


def collect_coverage() -> dict[str, list[str]]:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "req.json"
        subprocess.run(
            [sys.executable, "-m", "pytest", "--collect-only", "-q"],
            cwd=ROOT,
            env={**os.environ, "REQ_REPORT": str(report)},
            check=True,
            capture_output=True,
        )
        return json.loads(report.read_text())


def main() -> int:
    requirements = load_requirements(REQ_DIR)
    coverage = collect_coverage()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render_matrix(requirements, coverage))
    problems = check(requirements, coverage)
    for problem in problems:
        print(f"ERROR: {problem}")
    covered = sum(1 for r in requirements if coverage.get(r))
    print(f"Traceability: {covered}/{len(requirements)} requirements covered → {OUTPUT.name}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
